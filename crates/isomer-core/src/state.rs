//! Shared Labcoat Network state types
//!
//! Pure serde types describing services, accounts, and system status.

use serde::{Deserialize, Serialize};

/// Status of a managed service
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
#[serde(rename_all = "lowercase")]
pub enum ServiceStatus {
    Stopped,
    Starting,
    Running,
    Error(String),
}

/// Information about a single service
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ServiceInfo {
    pub id: String,
    pub name: String,
    pub status: String, // "stopped", "running", "error" // Simplified for frontend
    pub pid: Option<u32>,
    pub port: u16,
    pub uptime_secs: Option<u64>,
    pub version: Option<String>,
}

/// Whether, and where, a local client can have the built-in wallet sign.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct DevSignerInfo {
    /// Whether the dev signer answers with the built-in wallet right now.
    pub available: bool,
    /// The JSON-RPC endpoint that serves the methods.
    pub rpc: String,
    pub methods: Vec<String>,
    /// The built-in wallet's primary address, when available.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub address: Option<String>,
    /// Why it is not available.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub reason: Option<String>,
}

/// Overall system status
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SystemStatus {
    pub network: String,
    pub bitcoin_network: String,
    /// Chain-instance UUID; regenerated by `labcoat reset`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub instance_id: Option<String>,
    pub services: Vec<ServiceInfo>,
    pub block_height: u64,
    pub mempool_size: usize,
    pub is_ready: bool,
    /// The dev signer, while the network is running.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub dev_signer: Option<DevSignerInfo>,
}
