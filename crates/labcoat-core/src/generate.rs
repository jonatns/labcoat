    #[test]
    fn stale_generated_files_are_replaced_and_foreign_files_kept() {
        let root = std::env::temp_dir().join(format!("labcoat-generate-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&root);
        std::fs::create_dir_all(root.join("abi")).unwrap();
        std::fs::write(
            root.join("abi/removed-contract.ts"),
            format!("{GENERATED_HEADER}\nexport const gone = 1\n"),
        )
        .unwrap();
        std::fs::write(root.join("hand-written.ts"), "export const keep = 1\n").unwrap();

        let files = vec![GeneratedFile {
            path: "manifest.ts".to_string(),
            contents: format!("{GENERATED_HEADER}\nexport const MANIFEST = {{}}\n"),
        }];
        write_files(&root, &files).unwrap();

        assert!(root.join("manifest.ts").exists());
        assert!(root.join("hand-written.ts").exists());
        assert!(!root.join("abi/removed-contract.ts").exists());
        std::fs::remove_dir_all(root).ok();
    }
